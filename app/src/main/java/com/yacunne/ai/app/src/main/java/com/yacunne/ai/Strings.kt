fun resolveUiLang(setting: String): String {
    if (setting != "auto" && TABLES.containsKey(setting)) return setting
    return when (java.util.Locale.getDefault().language) {
        "rn" -> "rn"
        "rw" -> "rw"
        "fr" -> "fr"
        "sw" -> "sw"
        else -> "en"
    }
}

fun tx(key: String): String {
    return TABLES[UiLang.current]?.get(key) ?: EN[key] ?: key
}

